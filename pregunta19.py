def random_walk_test(series, name):
    print(f"\nRandom Walk Test for {name}:")
    diff_series = series.diff().dropna()
    var_original = np.var(series)
    var_diff = np.var(diff_series)
    print(f"  Variance of original series: {var_original:.4f}")
    print(f"  Variance of differenced series: {var_diff:.4f}")
    print("  Interpretation:")
    if var_diff < var_original:
        print(f"    - Differenced variance is smaller: {name} may not be a pure random walk")
    else:
        print(f"    - Similar variances: {name} may be a random walk")

