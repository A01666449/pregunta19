# b. Unit Root Tests
def unit_root_tests(series, name):
    result = {
        'name': name,
        'adf_stat': None,
        'adf_p': None,
        'adf_result': '',
        'kpss_stat': None,
        'kpss_p': None,
        'kpss_result': ''
    }

    print(f"\nUnit Root Tests for {name}:")

    # ADF Test
    try:
        adf_result = adfuller(series)
        result['adf_stat'] = adf_result[0]
        result['adf_p'] = adf_result[1]
        result['adf_result'] = 'Stationary' if adf_result[1] < 0.05 else 'Non-stationary'
        print("ADF Test:")
        print(f'  Statistic: {adf_result[0]:.4f}')
        print(f'  p-value: {adf_result[1]:.4f}')
        print(f'  Critical Values: {adf_result[4]}')
        print("  Interpretation:")
        if adf_result[1] < 0.05:
            print(f"    - p-value < 0.05: Reject null - {name} is stationary")
        else:
            print(f"    - p-value >= 0.05: Fail to reject null - {name} may be non-stationary")
    except ValueError as e:
        print(f"ADF Test failed for {name}: {e}")

    # KPSS Test
    try:
        kpss_result = kpss(series, regression='c')
        result['kpss_stat'] = kpss_result[0]
        result['kpss_p'] = kpss_result[1]
        result['kpss_result'] = 'Non-stationary' if kpss_result[1] < 0.05 else 'Stationary'
        print("\nKPSS Test:")
        print(f'  Statistic: {kpss_result[0]:.4f}')
        print(f'  p-value: {kpss_result[1]:.4f}')
        print(f'  Critical Values: {kpss_result[3]}')
        print("  Interpretation:")
        if kpss_result[1] < 0.05:
            print(f"    - p-value < 0.05: Reject null - {name} is non-stationary")
        else:
            print(f"    - p-value >= 0.05: Fail to reject null - {name} may be stationary")
    except ValueError as e:
        print(f"KPSS Test failed for {name}: {e}")

    return result

