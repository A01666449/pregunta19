# Engle-Granger Test
def engle_granger_test(series1, series2):
    print("\nCointegration Test (Engle-Granger):")
    try:
        score, p_value, _ = coint(series1, series2)
        print(f'  Test statistic: {score:.4f}')
        print(f'  p-value: {p_value:.4f}')
        print("  Interpretation:")
        if p_value < 0.05:
            print("    - p-value < 0.05: Reject null - GS3M and GS6M are cointegrated")
        else:
            print("    - p-value >= 0.05: Fail to reject null - GS3M and GS6M may not be cointegrated")
        return p_value < 0.05
    except ValueError as e:
        print(f"Engle-Granger test failed: {e}")
        return False

# Johansen Test
def johansen_test(df):
    print("\nCointegration Test (Johansen):")
    try:
        result = coint_johansen(df, det_order=0, k_ar_diff=1)
        print(f"  Trace Statistic: {result.lr1}")
        print(f"  Critical Values (90%, 95%, 99%): {result.cvt}")
        print("  Interpretation:")
        coint_rank = sum(result.lr1 > result.cvt[:, 1])  # Compare with 95% critical values
        if coint_rank > 0:
            print(f"    - Trace statistic exceeds 95% critical value for r=0: GS3M and GS6M are cointegrated")
        else:
            print(f"    - Trace statistic does not exceed 95% critical value: GS3M and GS6M may not be cointegrated")
        return coint_rank > 0, result
    except ValueError as e:
        print(f"Johansen test failed: {e}")
        return False, None

